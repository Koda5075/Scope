// All 6 supported languages only ever need a singular/plural split (no Slavic-style
// "few/many" tiers), so a plain count === 1 check is enough -- no need for Intl.PluralRules.
// Expects `${baseKey}One` / `${baseKey}Other` translation keys.
export function pluralLabel(count, t, baseKey) {
  return t[count === 1 ? `${baseKey}One` : `${baseKey}Other`];
}

export function gamesLabel(count, t) {
  return pluralLabel(count, t, 'gamesShort');
}
